"""Latin web subsets of the Venture Beyond variable fonts.

Reads the full distribution in typography/venture-beyond/dist/ttf/ (never modified) and writes
WOFF2 subsets for web delivery to public/fonts/venture-beyond/, plus SHA256SUMS, the OFL text
and a short README. Both variation axes (wght 100-900, wdth 62-125), all OpenType layout
features (kern, mark/mkmk, rvrn, ...) and the full name table are kept, so the subsets render
identically to the full fonts for every code point they contain.

    .venv/bin/python scripts/make_web_subsets.py          # from typography/venture-beyond/
"""
from __future__ import annotations

import hashlib
import shutil
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

from vb_config import VF_STYLES

HERE = Path(__file__).resolve().parent
VB = HERE.parent
REPO = VB.parent.parent
OUT = REPO / "public" / "fonts" / "venture-beyond"

# Latin: Basic Latin, Latin-1 Supplement, Latin Extended-A, combining diacritics (decomposed
# input), spacing modifiers, general punctuation, currency (incl. the rvrn-swapped signs),
# and the common symbols in Google Fonts' "latin" range.
UNICODES = (
    "U+0000-017F, U+0192, U+0218-021B, U+0237, U+02BB-02BC, U+02C6-02DD, U+0300-036F, "
    "U+1E9E, U+2000-206F, U+20A0-20C0, U+2113, U+2122, U+2126, U+212E, U+2190-2199, "
    "U+2202, U+2206, U+220F, U+2211-2215, U+2219-221A, U+221E, U+222B, U+2248, U+2260, "
    "U+2264-2265, U+25CA, U+FB01-FB02, U+FEFF, U+FFFD"
)


def options() -> subset.Options:
    o = subset.Options()
    o.flavor = "woff2"
    o.layout_features = ["*"]
    o.name_IDs = ["*"]
    o.name_languages = ["*"]
    o.name_legacy = True
    o.notdef_outline = True
    o.glyph_names = False
    o.legacy_kern = True
    o.drop_tables = []  # keep STAT, avar, HVAR, gasp, ...
    o.hinting = True  # the fonts are unhinted; nothing to drop, keep tables as-is
    return o


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    unicodes = subset.parse_unicodes(UNICODES)
    sums = []
    for style in VF_STYLES.values():
        src = VB / "dist" / "ttf" / style["ttf"]
        dst = OUT / style["woff2"].replace("-Variable.woff2", "-Latin.woff2")
        font = TTFont(src, recalcTimestamp=False)  # keep head.modified: reproducible output
        sub = subset.Subsetter(options())
        sub.populate(unicodes=unicodes)
        sub.subset(font)
        font.flavor = "woff2"
        font.save(dst)
        kept = len(font.getBestCmap())
        print(f"{dst.relative_to(REPO)}  {dst.stat().st_size:>7} bytes  {kept} code points "
              f"(full WOFF2 {(VB / 'dist' / 'woff2' / style['woff2']).stat().st_size} bytes)")
        sums.append(f"{sha256(dst)}  {dst.name}")
    (OUT / "SHA256SUMS").write_text("\n".join(sorted(sums, key=lambda s: s.split()[1])) + "\n")
    shutil.copyfile(VB / "LICENSE" / "OFL.txt", OUT / "OFL.txt")
    (OUT / "README.md").write_text(README)
    print(f"wrote {(OUT / 'SHA256SUMS').relative_to(REPO)}, OFL.txt, README.md")


README = """# Venture Beyond web subsets

Latin subsets of the three Venture Beyond variable fonts, for web delivery:

| File | CSS family / style |
|---|---|
| `VentureBeyond-Latin.woff2` | `Venture Beyond`, normal |
| `VentureBeyond-Italic-Latin.woff2` | `Venture Beyond`, italic |
| `VentureBeyond-Retalic-Latin.woff2` | `Venture Beyond Retalic`, normal (10° reverse slant) |

Both axes are kept: weight 100–900 and width 62–125. All OpenType features and the full
name table are kept too. The subset covers Basic Latin, Latin-1, Latin Extended-A, combining
marks, punctuation, currency and common symbols.

They're generated by `typography/venture-beyond/scripts/make_web_subsets.py` from the complete
distribution in `typography/venture-beyond/dist/`. That's the source for desktop installs and
for any other script; don't edit these files by hand. `SHA256SUMS` pins the output.

Venture Beyond is derived from Archivo by Omnibus-Type and is licensed under the SIL Open Font
License 1.1 (`OFL.txt`). Copyright notices are embedded in each font and listed in
`typography/venture-beyond/LICENSE/` and `FONTLOG.txt`.
"""

if __name__ == "__main__":
    main()
